/**
 * Returns the WAT text-format mnemonic for a core {@link Opcode}.
 * Returns `undefined` for opcodes with no single-token mnemonic.
 */
export function opcodeName(op: Opcode): string | undefined {
  return OPCODE_NAMES.get(op);
}

